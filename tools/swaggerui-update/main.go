// Command swaggerui-update vendors a swagger-ui-dist release into the swaggerui package.
//
// It downloads the npm tarball of the given version (or reads a local one), extracts the
// allow-listed files into the destination directory and writes a version.go file.
//
// Usage:
//
//	go run ./tools/swaggerui-update -version 5.33.2
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"context"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/go-faster/errors"
)

// files is the allow-list of files copied from the swagger-ui-dist package.
//
// Everything else (source maps, ES bundles, the sample index page) is not needed
// to serve the standalone layout and is intentionally skipped.
var files = []string{
	"LICENSE",
	"NOTICE",
	"favicon-16x16.png",
	"favicon-32x32.png",
	"oauth2-redirect.html",
	"oauth2-redirect.js",
	"swagger-ui-bundle.js",
	"swagger-ui-bundle.js.LICENSE.txt",
	"swagger-ui-standalone-preset.js",
	"swagger-ui-standalone-preset.js.LICENSE.txt",
	"swagger-ui.css",
}

func fetch(ctx context.Context, version string) ([]byte, error) {
	u := fmt.Sprintf("https://registry.npmjs.org/swagger-ui-dist/-/swagger-ui-dist-%s.tgz", version)
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, u, http.NoBody)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer func() {
		_ = resp.Body.Close()
	}()
	if resp.StatusCode != http.StatusOK {
		return nil, errors.Errorf("GET %s: unexpected status %s", u, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func extract(tarball []byte, out string) error {
	gz, err := gzip.NewReader(bytes.NewReader(tarball))
	if err != nil {
		return errors.Wrap(err, "gunzip")
	}
	defer func() {
		_ = gz.Close()
	}()

	seen := map[string]struct{}{}
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return errors.Wrap(err, "read tar")
		}
		if hdr.Typeflag != tar.TypeReg {
			continue
		}
		// npm tarballs put everything under "package/". Only top-level files
		// from the allow-list are extracted, and the destination path is built
		// from the allow-list entry rather than from the archive entry name.
		entry, ok := strings.CutPrefix(path.Clean(hdr.Name), "package/")
		if !ok || strings.Contains(entry, "/") {
			continue
		}
		idx := slices.Index(files, entry)
		if idx < 0 {
			continue
		}
		name := files[idx]

		data, err := io.ReadAll(tr)
		if err != nil {
			return errors.Wrapf(err, "read %q", name)
		}
		// The destination directory is a CLI flag and the file name is an allow-list entry.
		//#nosec G703
		if err := os.WriteFile(filepath.Join(out, name), data, 0o644); err != nil {
			return errors.Wrapf(err, "write %q", name)
		}
		seen[name] = struct{}{}
	}

	for _, name := range files {
		if _, ok := seen[name]; !ok {
			return errors.Errorf("file %q not found in tarball", name)
		}
	}
	return nil
}

func cleanDir(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return os.MkdirAll(dir, 0o750)
		}
		return err
	}
	for _, e := range entries {
		if err := os.RemoveAll(filepath.Join(dir, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

func writeVersion(p, version string) error {
	var b strings.Builder
	b.WriteString("// Code generated by tools/swaggerui-update; DO NOT EDIT.\n\n")
	b.WriteString("package swaggerui\n\n")
	b.WriteString("// Version is the version of the vendored swagger-ui-dist package.\n")
	fmt.Fprintf(&b, "const Version = %q\n", version)
	return os.WriteFile(p, []byte(b.String()), 0o644)
}

func run(ctx context.Context) error {
	var (
		version     = flag.String("version", "", "swagger-ui-dist version to download from npm")
		tarball     = flag.String("tarball", "", "Path to a local swagger-ui-dist tarball (skips download)")
		out         = flag.String("out", "swaggerui/dist", "Destination directory")
		versionFile = flag.String("version-file", "swaggerui/version.go", "Path to the generated version file")
	)
	flag.Parse()

	if *version == "" {
		return errors.New("-version is required")
	}

	var (
		data []byte
		err  error
	)
	if *tarball != "" {
		data, err = os.ReadFile(*tarball)
	} else {
		data, err = fetch(ctx, *version)
	}
	if err != nil {
		return errors.Wrap(err, "get tarball")
	}

	if err := cleanDir(*out); err != nil {
		return errors.Wrap(err, "clean")
	}
	if err := extract(data, *out); err != nil {
		return errors.Wrap(err, "extract")
	}
	if err := writeVersion(*versionFile, *version); err != nil {
		return errors.Wrap(err, "write version")
	}
	return nil
}

func main() {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()

	if err := run(ctx); err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "%+v\n", err)
		os.Exit(2)
	}
}
